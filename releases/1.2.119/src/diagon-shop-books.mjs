import {block as b, shape as p, line, casework} from './diagon-shop-brush.mjs';

// Native 1px grid and the Ollivanders upper-left light. Bowed oak shelves
// frame a burgundy reading nook, with moss paint and paper leading the eye.
const oak = ['#30282b','#574039','#78533e','#a47751','#c59764'];
const moss = ['#292f29','#37483a','#52674c','#718561','#a4a071'];
const brass = ['#4a3c31','#7f6240','#ac864b','#d8ae66','#f0d290'];
const red = ['#402c34','#623944','#884956','#ad626b','#c7827b'];
const paper = ['#6c4d39','#ad895b','#d6b781','#edcf99','#f5dfac'];
const bindings = [
  ['#674651','#915462','#b87979'], ['#405144','#637658','#81926c'],
  ['#594636','#886d46','#aa8a59'], ['#424858','#626a7d','#8c8b93'],
];
const define = (id,w,h,x,y,paint,extras={}) => ({id,w,h,x,y,paint,...extras});
const shelfBook = (c,x,y,w,h,index) => {
  const [dark,body,light] = bindings[index % bindings.length];
  b(c,x,y,w,h,dark);
  b(c,x+1,y+1,w-1,h-1,body);
  b(c,x+1,y+1,1,h-2,light);
  if (h>7) b(c,x+1,y+h-4,w-1,1,'#c5a677');
};

function bowedCase(c) {
  p(c,oak[0],[[-32,-62],[-24,-67],[-12,-70],[11,-70],[22,-67],[31,-62],[31,-4],[26,0],[-27,0],[-32,-4]]);
  p(c,oak[1],[[-29,-60],[-22,-64],[-10,-68],[9,-68],[22,-64],[28,-60],[28,-4],[-28,-4]]);
  p(c,oak[3],[[-31,-61],[-24,-66],[-12,-69],[8,-69],[21,-66],[30,-61],[24,-62],[13,-65],[-13,-65],[-26,-61]]);
  b(c,-25,-57,51,45,'#3e3231');
  for (const [i,y] of [-51,-37,-23].entries()) {
    const dimensions = [[5,10],[3,9],[6,12],[4,8],[4,11],[6,9],[3,12],[5,8],[4,10]];
    let x=-24;
    for (const [j,[w,h]] of dimensions.entries()) {
      shelfBook(c,x,y+6-h,w,h,(i*3+j)%4);
      x+=w+1;
    }
    p(c,oak[3],[[-25,y+6],[-10,y+8],[11,y+8],[26,y+6],[26,y+8],[11,y+11],[-10,y+11],[-25,y+8]]);
    b(c,-12,y+8,22,1,oak[4]);
  }
  b(c,-28,-58,3,52,oak[3]);
  b(c,25,-58,3,51,oak[2]);
  p(c,oak[2],[[-29,-9],[-12,-7],[11,-7],[29,-9],[28,-3],[-28,-3]]);
  b(c,-12,-7,25,1,oak[3]);
}

function lectern(c) {
  p(c,oak[0],[[-16,-34],[-12,-45],[12,-45],[16,-34],[12,-29],[6,-27],[5,-9],[12,-5],[11,0],[-11,0],[-12,-5],[-5,-9],[-6,-27],[-14,-29]]);
  p(c,oak[3],[[-13,-35],[-10,-43],[10,-43],[13,-35],[9,-32],[-10,-32]]);
  b(c,-12,-35,23,2,oak[4]);
  p(c,oak[2],[[-4,-29],[4,-29],[3,-7],[9,-4],[-9,-4],[-3,-8]]);
  b(c,-3,-28,2,16,oak[3]);
  b(c,-8,-4,15,2,oak[3]);
}

function folio(c,time=0) {
  const rise = Math.round(Math.sin(time*1.9)*1.35);
  c.save();
  c.translate(0,rise);
  p(c,red[0],[[-14,-6],[-12,-18],[-6,-20],[0,-17],[6,-20],[13,-18],[15,-6],[8,-3],[0,-4],[-8,-3]]);
  p(c,paper[2],[[-12,-7],[-10,-17],[-5,-18],[-1,-16],[-1,-6],[-6,-8]]);
  p(c,paper[3],[[0,-16],[5,-18],[11,-17],[13,-7],[7,-8],[1,-5]]);
  b(c,-8,-14,5,1,paper[1]);
  b(c,-9,-11,6,1,paper[1]);
  b(c,4,-14,5,1,paper[1]);
  b(c,4,-12,6,1,paper[1]);
  b(c,2,-21,1,2,brass[4]);
  b(c,15,-14,2,1,brass[3]);
  c.restore();
}

function bookStair(c) {
  const levels = [[-17,-26,15,8],[-15,-20,23,8],[-12,-14,27,8],[-10,-8,28,8]];
  for (const [i,[x,y,w,h]] of levels.entries()) {
    p(c,oak[0],[[x,y+3],[x+3,y],[x+w-2,y],[x+w,y+3],[x+w,y+h],[x,y+h]]);
    b(c,x+2,y+3,w-4,h-4,bindings[i][1]);
    b(c,x+2,y+3,w-5,1,bindings[i][2]);
    b(c,x+w-8,y+4,6,h-5,paper[2]);
    b(c,x+w-6,y+5,4,1,paper[1]);
    b(c,x+1,y+h-2,w-2,1,bindings[i][2]);
  }
}

function libraryCart(c) {
  p(c,oak[0],[[-24,-29],[-22,-37],[-17,-38],[-15,-32],[20,-32],[24,-28],[24,-7],[19,-4],[-19,-4],[-24,-7]]);
  b(c,-21,-26,43,18,oak[1]);
  for (let x=-18,i=0; x<18; x+=6,i++) shelfBook(c,x,-24-i%3*2,5,12+i%3*2,i+1);
  b(c,-21,-13,43,4,oak[3]);
  b(c,-20,-11,41,1,oak[4]);
  b(c,-22,-31,4,24,oak[3]);
  b(c,18,-29,3,24,oak[2]);
  for (const x of [-16,16]) {
    p(c,oak[0],[[x-4,-6],[x+3,-6],[x+4,-3],[x+3,0],[x-3,0],[x-5,-3]]);
    b(c,x-2,-4,4,2,brass[2]);
  }
}

function till(c) {
  casework(c,-45,0,90,32,8,moss);
  for (const [x,w] of [[-40,22],[-14,27],[17,21]]) {
    p(c,moss[1],[[x,-19],[x+w,-19],[x+w,-7],[x+2,-7],[x,-9]]);
    b(c,x+2,-18,w-4,1,moss[3]);
    b(c,x+4,-15,w-8,5,moss[2]);
  }
  b(c,16,-34,16,7,brass[0]);
  b(c,18,-36,11,8,brass[2]);
  b(c,18,-36,11,1,brass[4]);
  b(c,20,-33,6,2,oak[0]);
  b(c,18,-29,13,1,brass[3]);
}

