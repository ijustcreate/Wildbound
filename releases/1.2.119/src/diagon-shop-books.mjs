function scrollRack(c) {
  casework(c,-20,0,40,52,5,oak);
  b(c,-17,-43,34,36,oak[0]);
  for (const [i,y] of [-36,-25,-14].entries()) {
    b(c,-17,y+5,34,3,oak[2]);
    b(c,-16,y+5,29,1,oak[3]);
    for (const [j,x] of [-14,-5,4,12].entries()) {
      const offset=(i+j)%3;
      b(c,x,y+offset,6,6,paper[1]);
      b(c,x,y+offset,5,4,paper[2]);
      b(c,x+1,y+offset+1,3,2,paper[0]);
      b(c,x+1,y+offset,3,1,paper[3]);
    }
  }
}

