function polygon(c, color, points) {
  c.fillStyle = color;
  const ys = points.map(([, y]) => y);
  for (let y = Math.min(...ys); y < Math.max(...ys); y++) {
    const scan = y + .5;
    const intersections = [];
    for (let i = 0; i < points.length; i++) {
      const [ax, ay] = points[i];
      const [bx, by] = points[(i + 1) % points.length];
      if (scan >= Math.min(ay, by) && scan < Math.max(ay, by)) {
        intersections.push(ax + (scan - ay) * (bx - ax) / (by - ay));
      }
    }
    intersections.sort((a, b) => a - b);
    for (let i = 0; i < intersections.length; i += 2) {
      const left = Math.ceil(intersections[i] - .5);
      const right = Math.ceil(intersections[i + 1] - .5);
      c.fillRect(left, y, right - left, 1);
    }
  }
}

function brush(c) {
  return (color, ...points) => polygon(c, color, points);
}

// Distance along the edge and across its face, measured from the pommel.
function bladeBrush(c) {
  return (color, ...points) => polygon(c, color, points.map(([u, v]) => [8 + u + v, 39 - u + v]));
}

