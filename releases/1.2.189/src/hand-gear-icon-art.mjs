function paintBlade(c, style) {
  const p = bladeBrush(c);
  const { tip, shoulder, width, guard, steel, metal, jewel, hooked } = style;
  const [edge, shadow, face, light] = steel;
  const [guardEdge, guardShadow, guardFace, guardLight] = metal;
  p(INK, [-3,-2], [2,-3], [8,-2], [8,3], [1,3], [-3,2]);
  p(WOOD[1], [-1,-1], [8,-1], [8,2], [-1,2]);
  p(WOOD[2], [1,-1], [3,-1], [3,2], [2,2]);
  p(WOOD[2], [5,-1], [6,-1], [6,1], [5,2]);
  p(guardFace, [-2,-2], [0,-2], [1,2], [-2,2]);
  p(guardLight, [-2,-2], [0,-2], [0,-1], [-1,0]);

  // The dark back plane and thin honed face separate the edge from the body.
  p(edge, [8,-width+1], [shoulder,-width], [tip,0], [tip-3,width-1],
    [shoulder,width+1], [hooked?16:11,width+1], [10,hooked?width+3:width], [9,1]);
  p(shadow, [10,-width+2], [shoulder,-width+1], [tip-2,0], [tip-4,width-2],
    [shoulder,width], [12,width], [10,1]);
  p(face, [11,-width+2], [shoulder,-width+1], [tip-2,0], [tip-7,1],
    [13,1], [10,0]);
  p(light, [12,-width+2], [shoulder,-width+1], [tip-2,0],
    [shoulder,-width+2], [13,-width+3]);
  p(face, [15,1], [shoulder-2,1], [tip-5,0], [shoulder-2,2], [15,2]);
  if (hooked) p(face, [10,2], [17,2], [11,width+1], [10,width]);
  p(guardEdge, [7,-guard], [9,-guard-1], [11,-guard+1], [10,-2],
    [10,2], [11,guard-1], [9,guard+1], [7,guard]);
  p(guardShadow, [8,-guard], [10,-guard], [9,1], [10,guard], [8,guard]);
  p(guardFace, [8,-guard], [9,-guard], [9,0], [9,guard-1], [8,guard]);
  p(guardLight, [8,-guard], [9,-guard], [9,-2], [8,-2]);
  if (jewel) p(jewel, [7,-1], [9,-2], [11,0], [9,2], [7,1]);
}

