export function wizardCardActor(card,time=0){
 const loop=((time%5)+5)%5;
 const cast=card.pose==='cast'&&loop>=3.6;
 const faceX=card.pose==='idle' ? .04+.6*Math.sin(loop*2*Math.PI/5) : .27;
 return {
  id:`wizard-card-${card.id}`,name:card.name,kind:'player',sprite:'player',hp:1,x:0,y:0,
  faceX,faceY:1,moving:false,appearance:card.appearance,equipment:card.equipment,
  animationAction:cast?'cast':'idle',...(cast?{poseTime:(loop-3.6)/1.4}:{}),
 };
}
