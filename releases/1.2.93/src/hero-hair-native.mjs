export function hairDrawing(style,d,frame=0,action='idle'){
 if(style==='none')return {crown:[],rear:[],front:[],details:[]};
 const views=HAIR_CONTOURS[style];if(!views)return null;
 const mirror=d>4&&style!=='undercut'&&style!=='sidepart',index=mirror?8-d:d;
 let crown=style==='sidepart'&&d>4?partRight[d]:views[index];
 if(mirror)crown=crown.map(([x,y])=>[-x,y]);
 const rear=[],front=[],details=[],back=d>=3&&d<=5;
 const sway=['idle','sleep','death'].includes(action)?0:Math.round(Math.sin(frame*.7)*2)/2;
 const addTail=(anchor,shape,near=false)=>{
  const [x,y]=anchor,points=shape.map(([a,b])=>[x+a+sway*Math.max(0,b)/12,y+b]);(near?front:rear).push(points);
  details.push({type:'tie',x,y:y+.5,front:near});
  if(shape===braid)details.push({type:'braid',x,y:y+3,front:near});
 };
 if(style==='ponytail')addTail(anchorBack[d],tail);
 if(style==='braids')addTail(anchorBack[d],braid);
 if(style==='twinbraids'){addTail(anchorLeft[d],braid,d===0||d===6||d===7);addTail(anchorRight[d],braid,d===0||d===1||d===2);}
 if(style==='sideponytail')addTail(anchorRight[d],tail,d===0||d===1||d===2);
 if(style==='topknot'){
  const a=[0,-6.5],bun=[[-2,-1],[-2.5,-3],[-1.5,-4],[1,-4],[2.5,-3],[2,-1],[0,0]];
  crown=[crown,[[-1.5,-8],[1.5,-8],[1.5,-5],[-1.5,-5]],translate(bun,...a)];details.push({type:'tie',x:0,y:-6.5});
 }
 if(['long','waves','locs'].includes(style)&&!back){
  // The rear curtain sits behind shoulders; the main contour contains face-side locks.
  rear.push([[-4,-2],[4,-2],[5.5,6+sway],[4,10+sway],[-4,10-sway],[-5.5,6-sway]]);
 }
 return {crown:Array.isArray(crown[0]?.[0])?crown:[crown],rear,front,details};
}
