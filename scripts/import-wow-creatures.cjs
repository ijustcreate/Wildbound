// Transfer selected WoW skeletal motion to Wildbound's editable pixel joints.
// This reads only bone tracks. No mesh, texture, or material is rendered by the game.
const fs = require('node:fs');
const path = require('node:path');
const {loadM2} = require('./lib/wow-m2.cjs');
const root = path.resolve(__dirname, '..');
const sources = {
  spider: {
    file: 'assets/spider-wow/spider-1513626.m2', display: 35985, scale: 13, idle: 4,
    joints: {pelvis:1,chest:66,head:69,jawL:75,jawR:76,
      leg0L:6,knee0L:26,foot0L:34,leg1L:5,knee1L:25,foot1L:33,leg2L:4,knee2L:24,foot2L:32,leg3L:3,knee3L:23,foot3L:31,
      leg0R:9,knee0R:29,foot0R:37,leg1R:8,knee1R:28,foot1R:36,leg2R:10,knee2R:30,foot2R:38,leg3R:7,knee3R:27,foot3R:35},
    clips: {idle:4,walk:0,run:1,charge:1,windup:5,attack:5,bite:5,recover:5,hurt:6,snared:4,death:8},
  },
  boar: {
    file:'assets/boar-wow/boar-3978441.m2',display:193,scale:14,idle:1,
    joints:{pelvis:4,chest:5,neck:8,head:20,face:20,eyeL:20,eyeR:20,earL:28,earR:30,muzzle:70,nose:71,
      shoulderL:13,elbowL:21,frontPawL:41,shoulderR:14,elbowR:22,frontPawR:42,
      hipL:11,kneeL:19,hockL:26,rearPawL:40,hipR:9,kneeR:16,hockR:24,rearPawR:37,
      tailBase:7,tailMid:10,tailTip:25,hornBase:74,hornTip:74,smallHornBase:75,smallHornTip:75},
    clips:{idle:1,walk:2,run:0,charge:0,windup:3,attack:3,recover:3,hurt:5,snared:1,death:6},
  },
  elephant: {
    file:'assets/elephant-wow/trunks-122982.m2',display:61148,scale:12,idle:20,
    joints:{pelvis:1,chest:2,neck:6,head:12,jaw:14,eyeL:12,eyeR:12,earL:12,earR:12,
      shoulderL:11,elbowL:16,frontPawL:19,shoulderR:10,elbowR:15,frontPawR:18,
      hipL:5,kneeL:9,rearPawL:48,hipR:4,kneeR:8,rearPawR:13,
      tailBase:3,tailMid:7,tailTip:7,trunkBase:14,trunkMid:21,trunkTip:22,tuskL:12,tuskR:12},
    clips:{idle:20,walk:12,run:3,charge:3,attack:0,trumpet:5,hit:1,hurt:2,death:7},
  },
};
const output = {};
const round = n => Math.round(n*100)/100;
for(const [kind,spec] of Object.entries(sources)) {
  const m=loadM2(path.join(root,spec.file));
  const base=m.sample(spec.idle,0).positions;
  const clips={};
  for(const [action,index] of Object.entries(spec.clips)) {
    const seq=m.sequences[index],loop=['idle','walk','run','charge','snared'].includes(action);
    const count=Math.max(6,Math.min(18,Math.ceil(seq.duration/90)));
    const keys=[];
    for(let f=0;f<count;f++) {
      const t=seq.duration*(loop?f/count:f/(count-1));
      const positions=m.sample(index,t).positions;
      const rootDelta=positions[0].map((v,k)=>v-base[0][k]);
      const joints={};
      for(const [name,bone] of Object.entries(spec.joints)) {
        const delta=positions[bone].map((v,k)=>v-base[bone][k]-rootDelta[k]);
        // WoW X is forward and Y is lateral. Wildbound Y is forward and Z is up.
        const damping=kind==='spider'&&action==='death'?.4:kind==='boar'&&['attack','windup','recover'].includes(action)?.7:1;
        joints[name]=[round(delta[1]*spec.scale*damping),round(delta[0]*spec.scale*damping),round(delta[2]*spec.scale*damping)];
        if(kind==='spider'&&name.startsWith('foot')){
          if(action==='idle'||action==='snared')joints[name]=[0,0,0];
          else if(['walk','run','charge'].includes(action))joints[name][2]=joints[name][2]<2?0:joints[name][2];
          else if(action==='death')joints[name][0]+=round((name.endsWith('L')?1:-1)*9*f/(count-1));
        }
      }
      keys.push({frame:f,joints});
    }
    clips[action]={fps:round(count*1000/seq.duration),length:count,loop,keys};
  }
  output[kind]={displayId:spec.display,source:spec.file,clips};
}
const target=path.join(root,'src/wow-creature-motion-data.mjs');
fs.writeFileSync(target,'// Generated by scripts/import-wow-creatures.cjs from public Wowhead M2 bone tracks.\nexport const wowCreatureMotion = '+JSON.stringify(output)+';\n');
