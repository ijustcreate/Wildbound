const fs = require('node:fs');
const crypto = require('node:crypto');
const { loadM2 } = require('./lib/wow-m2.cjs');

const file = process.argv[2] || 'assets/slimes-wow/slime-3457112.m2';
const source = loadM2(file);
const scale = 20;
const names = { core: 26, crest: 48, rimL: 28, rimR: 31, eyeL: 70, eyeR: 71, gelL: 35, gelR: 36 };
const restCore = source.sample(null, 0).positions[names.core];
function nativePositions(sample) {
  return Object.fromEntries(Object.entries(names).map(([name, index]) => {
    const p = sample.positions[index];
    return [name, [(p[1] - restCore[1]) * scale, (p[0] - restCore[0]) * scale, (p[2] - restCore[2]) * scale]];
  }));
}
const rest = nativePositions(source.sample(null, 0));
const sequenceMap = [
  ['idle', 0, true], ['run', 1, true], ['walk', 2, true],
  ['hurt', 3, false], ['attack', 4, false], ['attack_alt', 5, false], ['death', 6, false],
];
const clips = {}, clipSource = {};
for (const [name, sequenceIndex, loop] of sequenceMap) {
  const seq = source.sequences[sequenceIndex];
  const seconds = seq.duration / 1000;
  const intervals = Math.max(2, Math.ceil(seconds * 15));
  const length = intervals + (loop ? 0 : 1), fps = intervals / seconds;
  clips[name] = { length, fps, loop, keys: Array.from({ length }, (_, frame) => {
    const pose = nativePositions(source.sample(sequenceIndex, frame / fps * 1000));
    return { frame, joints: Object.fromEntries(Object.keys(names).map(joint => [joint, pose[joint].map((v, axis) => v - rest[joint][axis])])) };
  }) };
  clipSource[name] = { sequence: sequenceIndex, animationId: seq.id, duration: seconds, loop, sourceName: ['Stand','Run','Walk','CombatWound','AttackUnarmed','AttackUnarmed','Death'][sequenceIndex] };
}
const model = {
  type: 'slime', name: 'World slime / WoW motion',
  joints: Object.fromEntries(Object.entries(names).map(([name]) => [name, { position: rest[name] }])),
  clips,
  palette: { body: '#74b832', shade: '#2d7136', light: '#b7e84b', highlight: '#e8f78b', outline: '#183d2c', eyes: '#f5ed9b', mouth: '#244c36', accent: '#d4ef65' },
  shape: { width: 21, depth: 17, height: 40, pixelStep: 2 },
  visibility: { eyeL: [true,true,true,true,false,false,false,true], eyeR: [true,true,true,false,false,false,true,true] },
  boneSprites: {}, renderOrder: {},
  provenance: {
    reference: 'https://www.wowhead.com/npc=222603/slime#modelviewer', npcId: 222603,
    displayId: 114801, modelFileId: 3457112,
    sourceUrl: 'https://wow.zamimg.com/modelviewer/live/m2/3457112.m2',
    sourceSha256: crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex'),
    sourceBones: source.bones.length, sourceSequences: source.sequences.length,
    distinctSequences: new Set(source.sequences.map(s => source.resolve(s.index))).size,
    mappedBones: names, scale, axes: 'WoW (X forward,Y left,Z up) -> Wildbound (Y,X,Z)',
    rootMotion: 'Native shape handles are relative to the body control; game locomotion owns horizontal travel.',
    clips: clipSource,
    rights: 'Blizzard source motion tracks; original Wildbound pixel artwork. The source mesh and texture are not bundled into the game.'
  }
};
const output = `// Generated by scripts/import-slime.cjs; see assets/slimes-wow/motion-provenance.json.\nexport default ${JSON.stringify(model)};\n`;
fs.writeFileSync('src/slime-data.mjs', output);
fs.writeFileSync('assets/slimes-wow/motion-provenance.json', JSON.stringify(model.provenance, null, 2) + '\n');
console.log(JSON.stringify({ output: 'src/slime-data.mjs', sourceBones: source.bones.length, sequences: sequenceMap.map(([name, index]) => ({name, animationId:source.sequences[index].id, duration:source.sequences[index].duration/1000})), sha256:model.provenance.sourceSha256 }, null, 2));
