import { readFileSync, writeFileSync } from 'node:fs';

const [input, output, name = 'PIXEL_FRAMES'] = process.argv.slice(2);
if (!input || !output || !/^[A-Z][A-Z0-9_]*$/.test(name || '')) {
  throw new Error('Usage: node scripts/compile-pixel-frames.mjs <animation.json> <module.mjs> [EXPORT_NAME]');
}
const animation = JSON.parse(readFileSync(input, 'utf8'));
if (!Array.isArray(animation.frames) || animation.frames.length !== 8) {
  throw new Error('Eight-direction pixel art must contain exactly eight frames');
}
const first = animation.frames[0].sprite;
if (!first || !Number.isInteger(first.width) || !Number.isInteger(first.height)) {
  throw new Error('Invalid eight-direction pixel sprite');
}
for (const [index, frame] of animation.frames.entries()) {
  if (frame.sprite.width !== first.width || frame.sprite.height !== first.height || frame.sprite.palette.join('|') !== first.palette.join('|')) {
    throw new Error(`Frame ${index} does not share the base dimensions and palette`);
  }
}
const symbols = '.odshabcdefghijklmnopqrstuvwxy';
if (first.palette.length > symbols.length) throw new Error('Pixel palette is too large to compile');
const frames = animation.frames.map(({ sprite }) => Array.from({ length: first.height }, (_, y) =>
  sprite.pixels.slice(y * first.width, (y + 1) * first.width).map(index => symbols[index]).join('')));
const source = [
  '// Generated by scripts/pixel-art.mjs and scripts/compile-pixel-frames.mjs; edit the recipe, not this file.',
  `export const ${name}={width:${first.width},height:${first.height},x:${first.x ?? 0},y:${first.y ?? 0},palette:${JSON.stringify(first.palette)},frames:${JSON.stringify(frames)}};`,
  '',
].join('\n');
writeFileSync(output, source);
