import test from 'node:test';
import assert from 'node:assert/strict';
import {Game} from '../src/core.mjs';
import {saveSession,restoreSession} from '../src/session.mjs';
import {enterWildLands} from '../src/wild-lands.mjs';
import {railwayBridgeState} from '../src/train-bridges.mjs';
import {leaveTrainTest,repairTrain,requestTrainRoute,tickTrainTest,enterTrainTest} from '../src/train-test.mjs';
import {nearestTrainTrack,trainCars} from '../src/train-track.mjs';

test('Public Wilds preserves party rewards, player position, train, and site claims through a serialized checkpoint',()=>{
 const game=new Game(()=>.5,{deferWorld:true}),player=game.addPlayer('keyboard');
 game.persist=()=>{};
 const persist=game.persist;
 assert.equal(enterWildLands(game,{persistent:true}).ok,true);
 assert.equal(game.players[0],player);
 assert.equal(game.persist,persist);
 Object.assign(player,{coins:77,xp:17,x:6600,y:3600,inventory:[{type:'iron_sword',qty:1}]});
 const rail=game.trainTest;
 Object.assign(rail,{distance:8200,time:18,speed:36,throttle:.6,engine:true,previous:new Map([[0,{jump:true}]])});
 rail.terrainStream={worker:()=>{}};
 rail.openOwlCages=new Set(['jungle-owl']);
 rail.cocoaTaken.add('compartments:one');
 rail.wildExploration={discovered:new Set(['fern-glade']),opened:new Set(['fern-glade'])};
 railwayBridgeState(rail.design).broken.add('wild-loop:14');
 const checkpoint=JSON.parse(JSON.stringify(saveSession(game)));
 assert.equal(checkpoint.state.trainTest,undefined);
 const restored=restoreSession(checkpoint),p=restored.players[0],t=restored.trainTest;
 assert.equal(t.persistent,true);
 assert.deepEqual([p.x,p.y,p.coins,p.xp],[6600,3600,77,17]);
 assert.equal(p.inventory[0].type,'iron_sword');
 assert.deepEqual([t.distance,t.speed,t.engine],[8200,36,true]);
 assert.ok(t.wildExploration.opened.has('fern-glade'));
 assert.ok(t.openOwlCages.has('jungle-owl'));
 assert.ok(t.cocoaTaken.has('compartments:one'));
 assert.ok(railwayBridgeState(t.design).broken.has('wild-loop:14'));
 assert.equal(t.previous.size,0);
 tickTrainTest(restored,.05,{});
 assert.ok(t.time>18);
 leaveTrainTest(restored);
 assert.equal(restored.trainTest,t,'developer return cannot discard public Wilds');
});

test('Repair after switching a railway junction resets all carriages to the current route',()=>{
 const game=new Game(()=>.5,{deferWorld:true});game.addPlayer('keyboard');
 assert.ok(enterTrainTest(game).ok);
 const train=game.trainTest,design=train.design;
 const a=design.nodes[2],b=design.nodes[3],branch={id:'test-branch',x:(a.x+b.x)/2+150,y:(a.y+b.y)/2+150,z:0};
 design.nodes.push(branch);
 const nodes=[...design.routes[0].nodes];nodes.splice(3,0,branch.id);
 design.routes.push({id:'branch',name:'Branch',nodes});
 assert.ok(requestTrainRoute(game,'branch').ok);
 const shared=design.nodes[1];
 train.distance=nearestTrainTrack(train.route,shared.x,shared.y).s-1;
 Object.assign(train,{speed:100,throttle:1,engine:true});
 tickTrainTest(game,.05,{});
 assert.equal(train.route.id,'branch');
 assert.equal(train.routeSegments.length,2);
 assert.ok(requestTrainRoute(game,'main').ok);
 assert.ok(repairTrain(game).ok);
 assert.equal(train.pendingRoute,null);
 assert.equal(train.routeSegments.length,1);
 assert.equal(train.routeSegments[0].route.id,'branch');
 const expected=trainCars({...train,routeSegments:undefined});
 assert.deepEqual(trainCars(train).map(({x,y})=>[x,y]),expected.map(({x,y})=>[x,y]));
});
