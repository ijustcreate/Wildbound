const { contextBridge, ipcRenderer } = require("electron");
contextBridge.exposeInMainWorld("desktop", {
  version: process.argv.find(arg => arg.startsWith('--wildbound-version='))?.slice('--wildbound-version='.length),
  preview: process.argv.includes('--preview'),
  testMode: process.argv.includes("--wildbound-test"),
  reportDiagnostics: (data) => ipcRenderer.send('live-diagnostics', data),
  loadProjectRigs: () => ipcRenderer.invoke('project-rigs-load'),
  saveProjectRigs: (data) => ipcRenderer.invoke('project-rigs-save', data),
  restoreBackup: () => ipcRenderer.invoke("restore-backup"),
  loadHouseDesigns: () => ipcRenderer.invoke("house-designs-load"),
  saveHouseDesigns: (data) => ipcRenderer.invoke("house-designs-save", data),
  loadProfiles: () => ipcRenderer.invoke("profiles-load"),
  loadSession: () => ipcRenderer.invoke("session-load"),
  saveSession: (data) => ipcRenderer.invoke("session-save", data),
  saveProfiles: (data) => ipcRenderer.invoke("profiles-save", data),
  hostRoom: () => ipcRenderer.invoke("room-host"),
  joinRoom: (address, name) => ipcRenderer.invoke("room-join", address, name),
  stopRoom: () => ipcRenderer.invoke("room-stop"),
  sendRoom: (data) => ipcRenderer.send("room-send", data),
  onRoom: (fn) => ipcRenderer.on("room-event", (_e, data) => fn(data)),
  listWorlds:()=>ipcRenderer.invoke('worlds-list'),
  loadWorld:id=>ipcRenderer.invoke('worlds-load',id),
  saveWorld:record=>ipcRenderer.invoke('worlds-save',record),
  openWorldFolder:()=>ipcRenderer.invoke('worlds-folder'),
  listWorldPacks:()=>ipcRenderer.invoke('world-packs-list'),
  worldPackAssets:id=>ipcRenderer.invoke('world-pack-assets',id),
  importWorldPack:()=>ipcRenderer.invoke('world-packs-import'),
  fullscreen: () => ipcRenderer.invoke("fullscreen"),
  claimController: (key) => ipcRenderer.invoke("controller-claim", key),
  releaseController: (key) => ipcRenderer.invoke("controller-release", key),
});
